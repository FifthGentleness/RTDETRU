# CPB-AIFI: Content-conditioned Positional Encoding + Block-sparse AIFI
# (AIFI_CondPEBlockSparse).
#
# Fuses two orthogonal AIFI improvements:
#   1. Block-sparse token routing (BlockSparse, sparse-vggt CVPR 2026):
#      each image-token query block attends to its own block plus its top-k
#      related key blocks.
#   2. Content-conditioned positional encoding: the static 2D sincos
#      embedding is kept as a POSITION ANCHOR, and a lightweight conv
#      generator produces a content-dependent positional modulation
#      (condPE, "positions that look at the image"):
#         pos(x) = sincos + gate * conv_dw3x3->GELU->conv1x1(x)
#      so crowded small-object regions can receive finer spatial labelling
#      than empty background regions, which plain sincos cannot express.
#
# Warm-up philosophy: the generator's last conv is zero-initialized and the
# modulation is scaled by a per-channel zero-init gate (LayerScale-style),
# so training starts EXACTLY at the BlockSparse baseline behavior and the
# model learns how much content-aware position to inject.
#
# Zero-overlap: no wavelet/frequency, no conv feature branch, no register
# tokens, no retrieval, no linear attention - only the positional embedding
# source and the attention routing are touched.

import math

import torch
import torch.nn as nn
import torch.nn.functional as F

__all__ = ['AIFI_CondPEBlockSparse']


class CondPE(nn.Module):
    """Content-conditioned positional modulation (zero-init gated).

    The static sincos embedding acts as the position anchor; this module
    adds a content-dependent correction generated by a local conv context.
    """

    def __init__(self, dim):
        super().__init__()
        self.dim = dim
        # Local spatial context: depthwise 3x3 sees the token's neighborhood,
        # so the generated position vector is aware of local crowding.
        self.local_ctx = nn.Conv2d(dim, dim, 3, padding=1, groups=dim,
                                   bias=False)
        self.gen = nn.Conv2d(dim, dim, 1, bias=True)
        nn.init.zeros_(self.gen.weight)
        nn.init.zeros_(self.gen.bias)
        # Per-channel zero-init gate (LayerScale style).
        self.gate = nn.Parameter(torch.zeros(dim))

    def forward(self, x_bhwc, b, h, w):
        """x_bhwc: (b, h, w, c) content map; returns (b, h*w, c)."""
        m = self.gen(self.local_ctx(x_bhwc.permute(0, 3, 1, 2)))
        m = F.gelu(m)
        m = m.permute(0, 2, 3, 1).reshape(b, h * w, self.dim)
        return self.gate * m


class BlockSparseAttention(nn.Module):
    """Block-sparse attention with query-block top-k routing."""

    def __init__(self, dim, num_heads=8, block_size=4, topk=4, dropout=0.0):
        super().__init__()
        if dim % num_heads != 0:
            raise ValueError(
                f'dim ({dim}) must be divisible by num_heads ({num_heads})')
        if block_size < 1 or topk < 1:
            raise ValueError('block_size and topk must be >= 1')

        self.dim = dim
        self.num_heads = num_heads
        self.head_dim = dim // num_heads
        self.scale = self.head_dim ** -0.5
        self.block_size = int(block_size)
        self.topk = int(topk)

        self.qkv = nn.Linear(dim, dim * 3, bias=True)
        self.proj = nn.Linear(dim, dim, bias=True)
        self.attn_drop = nn.Dropout(dropout)
        self.proj_drop = nn.Dropout(dropout)

    def forward(self, x):
        b, n, c = x.shape
        h, d = self.num_heads, self.head_dim
        bs = self.block_size
        num_blocks = math.ceil(n / bs)
        pad_len = num_blocks * bs - n
        npad = num_blocks * bs

        if pad_len:
            x = F.pad(x, (0, 0, 0, pad_len))

        qkv = self.qkv(x).chunk(3, dim=-1)
        q, k, v = [t.view(b, npad, h, d).permute(0, 2, 1, 3) for t in qkv]

        q_blk = x.view(b, num_blocks, bs, c).mean(dim=2)
        k_blk = q_blk
        block_logits = torch.matmul(q_blk, k_blk.transpose(-2, -1)) \
            * self.scale
        topk = min(self.topk, num_blocks)
        topk_idx = block_logits.topk(k=topk, dim=-1).indices

        block_mask = torch.zeros(
            b, num_blocks, num_blocks, dtype=torch.bool, device=x.device)
        block_mask.scatter_(-1, topk_idx, True)
        eye = torch.eye(num_blocks, dtype=torch.bool, device=x.device)
        block_mask = block_mask | eye.unsqueeze(0)

        token_mask = block_mask.repeat_interleave(bs, dim=1)
        token_mask = token_mask.repeat_interleave(bs, dim=2)
        token_mask = token_mask[:, :npad, :npad]
        if pad_len:
            valid = torch.zeros(b, npad, dtype=torch.bool, device=x.device)
            valid[:, :n] = True
            token_mask = token_mask & valid[:, None, :]

        logits = torch.matmul(q, k.transpose(-2, -1)) * self.scale
        logits = logits.masked_fill(~token_mask.unsqueeze(1), -1e4)
        attn = self.attn_drop(logits.softmax(dim=-1))
        out = torch.matmul(attn, v)
        out = out.permute(0, 2, 1, 3).reshape(b, npad, c)
        if pad_len:
            out = out[:, :n, :]
        return self.proj_drop(self.proj(out))


class AIFI_CondPEBlockSparse(nn.Module):
    """AIFI with content-conditioned positional encoding + block-sparse
    attention.

    Args:
        c1: Input and output channels.
        cm: Hidden dimension of the FFN.
        num_heads: Number of attention heads.
        block_size: Number of tokens per sparse block.
        topk: Number of key blocks attended by each query block.
        dropout: Dropout probability.
        act: Activation used by the FFN.
        normalize_before: Use pre-normalization if True.
    """

    def __init__(self, c1, cm=2048, num_heads=8, block_size=4, topk=4,
                 dropout=0.0, act=nn.GELU(), normalize_before=False):
        super().__init__()
        self.c1 = c1
        self.normalize_before = normalize_before
        self.cond_pe = CondPE(c1)
        self.attn = BlockSparseAttention(
            dim=c1, num_heads=num_heads, block_size=block_size, topk=topk,
            dropout=dropout)
        self.fc1 = nn.Linear(c1, cm)
        self.fc2 = nn.Linear(cm, c1)
        self.norm1 = nn.LayerNorm(c1)
        self.norm2 = nn.LayerNorm(c1)
        self.dropout = nn.Dropout(dropout)
        self.dropout1 = nn.Dropout(dropout)
        self.dropout2 = nn.Dropout(dropout)
        self.act = act

    @staticmethod
    def build_2d_sincos_position_embedding(w, h, embed_dim=256,
                                           temperature=10000.0):
        grid_w = torch.arange(int(w), dtype=torch.float32)
        grid_h = torch.arange(int(h), dtype=torch.float32)
        grid_w, grid_h = torch.meshgrid(grid_w, grid_h, indexing='ij')
        assert embed_dim % 4 == 0, \
            'Embed dimension must be divisible by 4 for 2D sincos embedding'
        pos_dim = embed_dim // 4
        omega = torch.arange(pos_dim, dtype=torch.float32) / pos_dim
        omega = 1.0 / (temperature ** omega)

        out_w = grid_w.flatten()[..., None] @ omega[None]
        out_h = grid_h.flatten()[..., None] @ omega[None]
        return torch.cat([torch.sin(out_w), torch.cos(out_w),
                          torch.sin(out_h), torch.cos(out_h)], dim=1)[None]

    def forward(self, x):
        b, c, h, w = x.shape
        if c != self.c1:
            raise ValueError(
                f'AIFI_CondPEBlockSparse expected {self.c1} channels, got {c}')

        x_bhwc = x.permute(0, 2, 3, 1)
        content = x_bhwc.reshape(b, h * w, c)
        pos = self.build_2d_sincos_position_embedding(w, h, c).to(
            device=x.device, dtype=x.dtype)
        src = content + pos + self.cond_pe(x_bhwc, b, h, w)

        if self.normalize_before:
            src = src + self.dropout1(self.attn(self.norm1(src)))
            src = src + self.dropout2(
                self.fc2(self.dropout(self.act(self.fc1(self.norm2(src))))))
        else:
            src = src + self.dropout1(self.attn(src))
            src = self.norm1(src)
            src = src + self.dropout2(
                self.fc2(self.dropout(self.act(self.fc1(src)))))
            src = self.norm2(src)

        return src.permute(0, 2, 1).view(b, c, h, w).contiguous()

    def extra_repr(self):
        return (f'c1={self.c1}, num_heads={self.attn.num_heads}, '
                f'block_size={self.attn.block_size}, topk={self.attn.topk}, '
                f'cond_pe=zero-init gated conv')
